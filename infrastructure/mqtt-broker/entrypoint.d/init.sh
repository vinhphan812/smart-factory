#!/bin/sh
# Entrypoint for eclipse-mosquitto:2 container.
# Generates mosquitto.conf and credentials at container start.
# This script MUST write into /mosquitto/config (the conf volume),
# because mosquitto.conf references include_dir /mosquitto/config/conf.d
# and the conf.d directory is on the same volume.

set -e

CONF_DIR="/mosquitto/config"
CONF_FILE="${CONF_DIR}/mosquitto.conf"
CONF_D="${CONF_DIR}/conf.d"
PASSWD_FILE="${CONF_DIR}/passwd"
ACL_FILE="${CONF_DIR}/acl"

# ---------------------------------------------------------------------------
# Helper: write mosquitto.conf
# ---------------------------------------------------------------------------
write_mosquitto_conf() {
    echo "[inf] Generating ${CONF_FILE}"

    # Determine TLS settings
    TLS_ENABLED="${MQTT_TLS_ENABLED:-false}"
    BIND_HOST="${MQTT_BIND_ADDRESS:-0.0.0.0}"
    BIND_PORT="${MQTT_PORT:-1883}"
    TLS_PORT=""
    TLS_ARGS=""
    if [ "$TLS_ENABLED" = "true" ]; then
        TLS_PORT="listener ${MQTT_TLS_PORT:-8883} ${MQTT_TLS_LISTENER_ADDRESS:-0.0.0.0}"
        TLS_ARGS="
cafile /mosquitto/certs/ca.crt
certfile /mosquitto/certs/server.crt
keyfile /mosquitto/certs/server.key
require_certificate false"
    fi

    # Build mosquitto.conf
    cat > "${CONF_FILE}" << EOF
# mosquitto.conf — generated by entrypoint
# NOTE: Do not edit this file directly. Changes will be lost on container
# restart. Modify the template in infrastructure/mqtt-broker/entrypoint.d/init.sh
# or add files to ${CONF_D}/ (they are included at the bottom).

# Persistence
persistence true
persistence_location /mosquitto/data/

# Logging
log_dest stdout
log_type error
log_type warning
log_type notice
log_timestamp_format %Y-%m-%dT%H:%M:%S

# Allow anonymous only if no credentials are configured (dev fallback)
allow_anonymous false

# Per-connection limits
max_keepalive 60
max_inflight_messages 20
max_queued_messages 1000
max_packet_size 32768

# ---------------------------------------------------------------------------
# Listeners
# ---------------------------------------------------------------------------
listener ${BIND_PORT} ${BIND_HOST}
${TLS_PORT}${TLS_ARGS}

# ---------------------------------------------------------------------------
# Security
# ---------------------------------------------------------------------------
password_file ${PASSWD_FILE}
acl_file ${ACL_FILE}

# ---------------------------------------------------------------------------
# Include additional config from conf.d/
# ---------------------------------------------------------------------------
include_dir ${CONF_D}
EOF

    echo "[inf] Wrote ${CONF_FILE}"
}

# ---------------------------------------------------------------------------
# Helper: generate password file
# ---------------------------------------------------------------------------
write_passwd() {
    echo "[inf] Generating ${PASSWD_FILE}"

    : > "${PASSWD_FILE}"

    # Admin (mosquitto_sub/pub admin tools — not used by bridge/gateway)
    if [ -n "${MQTT_ADMIN_USERNAME}" ] && [ -n "${MQTT_ADMIN_PASSWORD}" ]; then
        mosquitto_passwd -b "${PASSWD_FILE}" "${MQTT_ADMIN_USERNAME}" "${MQTT_ADMIN_PASSWORD}"
        echo "[inf] Added admin credential: ${MQTT_ADMIN_USERNAME}"
    fi

    # Bridge credential
    if [ -n "${MQTT_BRIDGE_USERNAME}" ] && [ -n "${MQTT_BRIDGE_PASSWORD}" ]; then
        mosquitto_passwd -b "${PASSWD_FILE}" "${MQTT_BRIDGE_USERNAME}" "${MQTT_BRIDGE_PASSWORD}"
        echo "[inf] Added bridge credential: ${MQTT_BRIDGE_USERNAME}"
    fi

    # Gateway credential
    if [ -n "${MQTT_GW_USERNAME}" ] && [ -n "${MQTT_GW_PASSWORD}" ]; then
        mosquitto_passwd -b "${PASSWD_FILE}" "${MQTT_GW_USERNAME}" "${MQTT_GW_PASSWORD}"
        echo "[inf] Added gateway credential: ${MQTT_GW_USERNAME}"
    fi
}

# ---------------------------------------------------------------------------
# Helper: generate ACL file
# ---------------------------------------------------------------------------
write_acl() {
    echo "[inf] Generating ${ACL_FILE}"

    # NOTE on env vars in ACL files:
    # Mosquitto ACL files do NOT expand environment variables.
    # The bridge credential's username MUST literally match its deviceId.
    #
    # Example: MQTT_BRIDGE_USERNAME=ukit-00000000
    #   The mosquitto.conf MUST have:
    #     user ukit-00000000
    #     topic read smart-factory/ukit-00000000/command/down
    #
    # If you add a second bridge (deviceId=ukit-00000001), add a second
    # user block with username ukit-00000001 and its deviceId-specific topic.
    #
    # Wildcard + in the subscriber topic is NOT valid for ACL topic matching:
    #   WRONG: topic read smart-factory/+/command/down  ← allows ANY deviceId
    #   RIGHT: topic read smart-factory/ukit-00000000/command/down  ← device-specific
    #
    # See infrastructure/mqtt-broker/docs/acl-design.md for full rationale.

    : > "${ACL_FILE}"

    # --- Admin ---
    # Full access for admin credential (used for testing only)
    if [ -n "${MQTT_ADMIN_USERNAME}" ]; then
        cat >> "${ACL_FILE}" << EOF
# Admin: full access (use only for management/testing, not in production)
user ${MQTT_ADMIN_USERNAME}
topic readwrite smart-factory/#
topic readwrite \$SYS/#

EOF
    fi

    # --- Bridge ---
    # ACL for bridge credential bound to MQTT_BRIDGE_USERNAME (which == deviceId).
    # Username is written LITERALLY — mosquitto does not expand env vars in ACL.
    # See docs/acl-design.md for rationale and migration steps.
    if [ -n "${MQTT_BRIDGE_USERNAME}" ]; then
        cat >> "${ACL_FILE}" << EOF
# Bridge credential: ${MQTT_BRIDGE_USERNAME}
# Rationale: the bridge subscribes to its own command/down topic only.
# - subscribe to own command/down (commands arrive from gateway/operator)
# - publish own result topics (ACK, telemetry, status)
# - MUST NOT be able to read another device's command/down
#
# IMPORTANT: If MQTT_BRIDGE_USERNAME changes (e.g. to ukit-00000001),
# you MUST also update this ACL block's topic line to match.
# See infrastructure/mqtt-broker/docs/acl-design.md.
user ${MQTT_BRIDGE_USERNAME}
topic read smart-factory/${MQTT_BRIDGE_USERNAME}/command/down
topic write smart-factory/${MQTT_BRIDGE_USERNAME}/command/ack
topic write smart-factory/${MQTT_BRIDGE_USERNAME}/telemetry
topic write smart-factory/${MQTT_BRIDGE_USERNAME}/status

EOF
    fi

    # --- Gateway ---
    if [ -n "${MQTT_GW_USERNAME}" ]; then
        cat >> "${ACL_FILE}" << EOF
# Gateway credential: ingest telemetry, status, ACKs across ALL devices.
# Gateway MUST NOT publish to bridge topics (bridge owns those).
user ${MQTT_GW_USERNAME}
topic read smart-factory/+/command/ack
topic read smart-factory/+/telemetry
topic read smart-factory/+/status
topic read smart-factory/+/heartbeat
# No write — gateway ingests only, it does not originate commands directly.
# Commands go through the command/down path (operator/gateway → bridge).

EOF
    fi

    echo "[inf] Wrote ${ACL_FILE}"
}

# ---------------------------------------------------------------------------
# Ensure conf.d directory exists (mosquitto include_dir directive)
# ---------------------------------------------------------------------------
mkdir -p "${CONF_D}"

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
write_mosquitto_conf
write_passwd
write_acl

# TLS configuration must be checked against the actual service environment,
# rather than a helper-local variable, before starting Mosquitto.
if [ "${MQTT_TLS_ENABLED:-false}" = "true" ]; then
    MISSING=""
    [ ! -f "/mosquitto/certs/ca.crt" ]     && MISSING="${MISSING} ca.crt"
    [ ! -f "/mosquitto/certs/server.crt" ]  && MISSING="${MISSING} server.crt"
    [ ! -f "/mosquitto/certs/server.key" ]  && MISSING="${MISSING} server.key"
    if [ -n "${MISSING}" ]; then
        echo "[ERROR] TLS enabled but certificate files missing:${MISSING}"
        echo "[ERROR] Run: cd infrastructure/mqtt-broker/config/tls && ./generate-certs.sh"
        exit 1
    fi
    echo "[inf] TLS certificates validated."
fi

echo "[inf] Mosquitto configuration complete."
echo "[inf] Starting mosquitto with config ${CONF_FILE}"
exec mosquitto -c "${CONF_FILE}"
